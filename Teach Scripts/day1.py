# 1. PRINT() FUNCTION
# -------------------
# The print() function is used to display output on the screen.

print("Hello World!")


# 2. PRINTING MULTIPLE VALUES
# ---------------------------
# We can print multiple values using commas.
# By default, Python separates them with a space.

print("A", "B")


# 3. SEP PARAMETER
# ----------------
# sep stands for separator.
# It specifies what should be printed between multiple values.
# Default value of sep is a space.

print("A", "B", sep=":")


# 4. END PARAMETER
# ----------------
# end specifies what should be printed at the end of a print statement.
# By default, end is a new line (\n).

print("Hello", end=" ")
print("World!")

# Output: Hello World!